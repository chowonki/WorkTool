def build(vendor, name):
    wb = Workbook()
    ws = wb.active
    ws.title = "탁송기한"
    head = [""] * 45
    for i, v in HEAD[vendor].items():
        head[i] = v
    ws.append(head)
    for d in DATA[vendor]:
        row = [""] * 45
        row[0], row[1] = d[0], d[1]
        if vendor == "A":
            row[2], row[3], row[10], row[11], row[41] = d[2], d[3], d[4], d[5], d[6]
