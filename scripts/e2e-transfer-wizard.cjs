const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const base='http://127.0.0.1:8765';
try{
 const context=await browser.newContext({acceptDownloads:true,viewport:{width:1366,height:970}});
 const page=await context.newPage();
 page.on('dialog',dialog=>dialog.accept());
 const inner=()=>page.frameLocator('#transferWorkflowFrame');
 await page.goto(base+'/transfer-input.html');
 await inner().locator('#raw').waitFor({state:'visible'});
 await inner().locator('#raw').fill('123가4567\n국민은행\n123-456-789012\n35,000원');
 await inner().locator('#parse').click();
 await page.waitForURL('**/transfer-review.html',{timeout:10000});
 const bank=inner().locator('select[data-k="bank"]').first();
 await bank.waitFor({state:'visible'});
 assert.equal(await bank.inputValue(),'국민은행','detected bank should be selected automatically');
 const bankCount=await bank.locator('option').count();
 assert.ok(bankCount>=25,'bank dropdown should contain the full supported list');
 await bank.selectOption('신한은행');
 assert.equal(await bank.inputValue(),'신한은행');
 await bank.selectOption('국민은행');
 console.log('Automatic step transition and full bank dropdown passed; banks:',bankCount);
 const amount=inner().locator('input[data-k="amount"]').first();
 await amount.waitFor({state:'visible'});
 assert.equal(await amount.inputValue(),'35000');
 assert.equal(await inner().locator('input[data-k="outMemo"]').first().inputValue(),'123가4567');
 await inner().locator('input[data-k="account"]').first().fill('123456789012');
 await page.locator('.stage-actions a[href="./transfer-download.html"]').click();
 await page.waitForURL('**/transfer-download.html');
 const downloadButton=inner().locator('#download');
 await downloadButton.waitFor({state:'visible'});
 assert.equal(await downloadButton.isEnabled(),true,'valid draft should be downloadable');
 const download=page.waitForEvent('download',{timeout:10000});
 await downloadButton.click();
 const dl=await download;
 assert.match(dl.suggestedFilename(),/\.xlsx$/);
 console.log('Bank file created:',dl.suggestedFilename());
 await page.locator('.stage-actions a[href="./transfer-review.html"]').click();
 await page.waitForURL('**/transfer-review.html');
 assert.equal(await inner().locator('input[data-k="amount"]').first().inputValue(),'35000');
 assert.equal(await inner().locator('input[data-k="inMemo"]').first().inputValue(),'123가4567');
 await page.reload();
 await inner().locator('input[data-k="amount"]').first().waitFor({state:'visible'});
 assert.equal(await inner().locator('input[data-k="account"]').first().inputValue(),'123456789012');
 console.log('Existing draft preserved through all three routes, download, back, reload');
 const context2=await browser.newContext({viewport:{width:390,height:844}});
 const memoPage=await context2.newPage();
 memoPage.on('dialog',dialog=>dialog.accept());
 await memoPage.goto(base+'/transfer-input.html');
 const memoInner=()=>memoPage.frameLocator('#transferWorkflowFrame');
 await memoInner().locator('#raw').fill('국민은행\n123-456-789012\n35,000원');
 await memoInner().locator('#parse').click();
 await memoInner().locator('#missingPlateDialog').waitFor({state:'visible'});
 await memoInner().locator('#missingPlateModeMemo').check();
 await memoInner().locator('#missingPlateInput').fill('고객 환급금');
 await memoInner().locator('#missingPlateApply').click();
 await memoPage.waitForURL('**/transfer-review.html',{timeout:10000});
 assert.equal(await memoInner().locator('select[data-k="bank"]').first().inputValue(),'국민은행');
 assert.equal(await memoInner().locator('input[data-k="outMemo"]').first().inputValue(),'');
 assert.equal(await memoInner().locator('input[data-k="inMemo"]').first().inputValue(),'고객 환급금');
 const size=await memoPage.locator('#transferWorkflowFrame').evaluate(el=>({w:el.offsetWidth,h:el.offsetHeight}));
 assert.ok(size.w>300&&size.w<450);
 assert.ok(size.h>=410,'frame should expand with content');
 console.log('Mobile memo-only flow passed; frame size:',size);
 await memoPage.locator('.stage-actions a[href="./transfer-download.html"]').click();
 await memoPage.waitForURL('**/transfer-download.html');
 await memoPage.locator('#workflowRestart').click();
 await memoPage.waitForURL('**/transfer-input.html');
 const info=await memoPage.evaluate(()=>sessionStorage.getItem('worktool.transfer.wizard.v1'));
 assert.ok(!info || JSON.parse(info).state.rows.length===0,'reset should not preserve any sensitive rows');
 console.log('New-task reset cleared transfer rows');
 await context.close();
 await context2.close();
}catch(e){
 console.error('Transfer wizard E2E FAILED:',e);
 throw e;
}finally{await browser.close()}
})().catch(()=>{process.exitCode=1});
